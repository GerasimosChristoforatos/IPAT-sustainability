"""results/key_numbers.md: every number the paper quotes, read from the results CSVs.

Each row: quantity, value (two significant figures unless a count), unit, frame,
uncertainty, the CSV it comes from, and the upstream source. Regenerated by `make all`,
so prose and figures cannot drift from the computations.
"""
import math
from pathlib import Path

import numpy as np
import pandas as pd

import load
import scenarios

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"


def sig(x, n=2):
    if x is None or (isinstance(x, float) and (math.isnan(x))):
        return "n/a"
    if math.isinf(x):
        return "floor fails"
    if x == 0:
        return "0"
    d = n - int(math.floor(math.log10(abs(x)))) - 1
    v = round(x, d)
    return f"{v:,.{max(d, 0)}f}"


def pct(x, n=2):
    return f"{sig(100 * x, n)} %"


def main():
    cfg = load.load_config()
    y = cfg["years"]["activity"]
    units = pd.read_csv(load.PROC / f"units_{y}.csv").set_index("unit")
    budget = pd.read_csv(load.PROC / "carbon_budget.csv")
    pop = pd.read_csv(load.PROC / "population.csv").set_index("label")
    rq1 = pd.read_csv(RES / "rq1_burn_rate.csv")
    rr = pd.read_csv(RES / "rq1_required_rate.csv")
    rq2 = pd.read_csv(RES / "rq2_floor.csv").set_index("route")
    rq3 = pd.read_csv(RES / "rq3_materialism.csv")
    rq4 = pd.read_csv(RES / "rq4_cost_of_existing.csv")
    rq5 = pd.read_csv(RES / "rq5_required_dematerialism.csv")
    rq6 = pd.read_csv(RES / "rq6_frontier.csv")
    mc = pd.read_csv(RES / "montecarlo_required_dematerialism.csv")
    H, T = cfg["carbon_budget"]["horizon_years"], 1.7
    b = budget[np.isclose(budget.likelihood, 0.5)].set_index("target_degC").budget_GtCO2
    rows = []

    def add(q, v, unit, frame, unc, csv, src):
        rows.append((q, v, unit, frame, unc, csv, src))

    # 1 allowance and emissions
    add("Remaining CO₂ budget from 2026, 1.5 / 1.7 / 2.0 °C (50 %)", f"{b[1.5]:.0f} / {b[1.7]:.0f} / {b[2.0]:.0f}", "Gt CO₂",
        "-", f"33–67 %: {budget[(budget.target_degC == 1.7) & np.isclose(budget.likelihood, 0.67)].budget_GtCO2.iloc[0]:.0f}–"
             f"{budget[(budget.target_degC == 1.7) & np.isclose(budget.likelihood, 0.33)].budget_GtCO2.iloc[0]:.0f} (1.7 °C)",
        "data/processed/carbon_budget.csv", "Forster et al. 2026, Table 8; IGCC data repository")
    add("Allowance Iᵖˡ, 1.7 °C, 50-year horizon", sig(b[1.7] / H), "Gt CO₂/yr", "static", "horizon 25 / 100 yr: "
        f"{sig(b[1.7] / 25)} / {sig(b[1.7] / 100)}", "data/processed/carbon_budget.csv", "derived (budget ÷ horizon)")
    add("World consumption-based CO₂, 2022", sig(units.loc["World"].I_kgCO2 / 1e12), "Gt CO₂/yr", "-", "-",
        f"data/processed/units_{y}.csv", "OWID / Global Carbon Budget 2026")
    add("Carbon intensity T, world 2022", sig(units.loc["World"].T_kgCO2_per_int2011usd), "kg CO₂ per 2011 int-$", "-", "-",
        f"data/processed/units_{y}.csv", "derived: I / (P·A)")
    # 2 floor and cost of existing
    c = rq2.loc["CENTRAL"]
    add("Floor Aᵉˢˢ (median of six routes)", sig(c.A_ess_int2011usd_per_cap), "2011 int-$ per person per yr", "-",
        f"route range {sig(c.A_ess_low_int2011usd_per_cap)}–{sig(c.A_ess_high_int2011usd_per_cap)}",
        "results/rq2_floor.csv", "Kikstra 2021; Millward-Hopkins 2025; Hickel & Sullivan 2024; Vélez-Henao 2026; Chancel 2022")
    add("Floor as share of world mean (φ)", sig(c.phi), "-", "-", f"{sig(c.phi_low)}–{sig(c.phi_high)}",
        "results/rq2_floor.csv", "derived")
    s4 = rq4[(rq4.frame == "static") & (rq4.P_label == "now") & (rq4.T_scenario == "Today") & (rq4.target_degC == T)].iloc[0]
    add("Cost of existing at today's T (everyone at Aᵉˢˢ)", sig(s4.cost_of_existing_GtCO2_per_yr_central), "Gt CO₂/yr", "static",
        f"{sig(s4.cost_of_existing_GtCO2_per_yr_low)}–{sig(s4.cost_of_existing_GtCO2_per_yr_high)}",
        "results/rq4_cost_of_existing.csv", "derived")
    add("Cost of existing ÷ Iᵖˡ, today's T, 1.7 °C", sig(s4.cost_over_budget_central), "×", "static",
        f"{sig(s4.cost_over_budget_low)}–{sig(s4.cost_over_budget_high)} (floor range)", "results/rq4_cost_of_existing.csv", "derived")
    p4 = rq4[(rq4.frame == "path") & (rq4.T_scenario == "BAU") & (rq4.target_degC == T)].set_index("P_label")
    add("Cost of existing, cumulative ÷ budget, T falling at the historical rate, 1.7 °C",
        f"{sig(p4.loc['now'].cost_over_budget_central)} (peak population: {sig(p4.loc['peak'].cost_over_budget_central)})", "×",
        "path", f"{sig(p4.loc['now'].cost_over_budget_low)}–{sig(p4.loc['now'].cost_over_budget_high)} (floor range)",
        "results/rq4_cost_of_existing.csv", "derived")
    # 3 materialism
    w = rq3[(rq3.method == "group means") & (rq3.A_ess_level == "central") & (rq3.group == "World")].iloc[0]
    wl = rq3[(rq3.method == "group means") & (rq3.group == "World")].set_index("A_ess_level")
    sm = rq3[(rq3.method == "Lorenz fit: singh_maddala") & (rq3.A_ess_level == "central")].set_index("group")
    add("Share of world CO₂ above the floor (lower bound)", pct(w.share_of_world_above_floor), "-", "-",
        f"{pct(wl.loc['high'].share_of_world_above_floor)}–{pct(wl.loc['low'].share_of_world_above_floor)} (floor range); "
        f"Lorenz fit {pct(sm.loc['World'].share_of_world_above_floor)}", "results/rq3_materialism.csv", "Chancel 2022 distribution")
    add("CO₂ above the floor", sig(w.above_floor_GtCO2), "Gt CO₂/yr", "-", "-", "results/rq3_materialism.csv", "derived")
    add("Richest 10 %'s share of above-floor CO₂", pct(sm.loc[["top1", "next9"]].above_floor_GtCO2.sum() / sm.loc["World"].above_floor_GtCO2),
        "-", "-", "Singh–Maddala fit", "results/rq3_materialism.csv", "Chancel 2022 distribution")
    add("Floor deficit of the poorest half", sig(sm.loc["World"].unmet_floor_GtCO2), "Gt CO₂/yr", "-", "Singh–Maddala fit",
        "results/rq3_materialism.csv", "derived")
    # 4 technology alone
    tr = rr[(rr.P_label == "now") & (rr.target_degC == T)].set_index(["reference", "case"])
    ta = "technology alone (A_dem = 1)"
    add("Required sustained decline of T, technology alone, 1.7 °C: US / EU27 / world lifestyle",
        f"{pct(tr.loc[('US', ta)].required_rate)} / {pct(tr.loc[('EU27', ta)].required_rate)} / {pct(tr.loc[('World', ta)].required_rate)}",
        "per yr", "path", "-", "results/rq1_required_rate.csv", "derived")
    hist = cfg["t_scenarios"]["BAU"]["rate"]
    d = pd.read_csv(load.RAW / "owid-co2-data.csv", usecols=["country", "year", "gdp", "consumption_co2"])
    w0 = d[(d.country == "World") & d.year.isin([2000, y])].set_index("year")
    tT = w0.consumption_co2 / w0.gdp
    own = 1 - (tT[y] / tT[2000]) ** (1 / (y - 2000))
    add("Historical decline of T (scenario value)", pct(hist), "per yr", "-",
        f"own data, consumption-based world T 2000–{y}: {pct(own, 3)}", "config.yaml; data/raw/owid-co2-data.csv",
        "brief / PwC NZEI 2024 (not verified in a primary PwC document)")
    us_path = rq1[(rq1.frame == "path") & (rq1.reference == "US") & (rq1.P_label == "now") & (rq1.T_scenario == "Today")
                  & (rq1.target_degC == T)].iloc[0]
    add("Years until the 1.7 °C budget is used up, US lifestyle for all at today's T", sig(us_path.years_to_exhaustion), "yr",
        "path", "-", "results/rq1_burn_rate.csv", "derived")
    # 5 dematerialism exists
    o = rq6[(rq6.spec == "main") & (rq6.A_ess_level == "central")].set_index(["method", "reference"])
    q = "quantile regression tau=0.9"
    add("Observed Aᵈᵉᵐ, US / EU27 (frontier, τ = 0.9)", f"{sig(o.loc[(q, 'US')].A_dem_observed)} / {sig(o.loc[(q, 'EU27')].A_dem_observed)}",
        "-", "-", f"95 % CI US {sig(o.loc[(q, 'US')].A_dem_observed_ci_low)}–{sig(o.loc[(q, 'US')].A_dem_observed_ci_high)}, "
        f"EU27 {sig(o.loc[(q, 'EU27')].A_dem_observed_ci_low)}–{sig(o.loc[(q, 'EU27')].A_dem_observed_ci_high)}",
        "results/rq6_frontier.csv", "WHR 2026 data (2021–2023 window); OWID GDP")
    rob = rq6[(rq6.A_ess_level == "central") & (rq6.reference == "US")].set_index("spec")
    add("Observed Aᵈᵉᵐ, US, robustness", f"τ = 0.95: {sig(rob.loc['robustness: tau'].A_dem_observed)}; "
        f"2023–2025 ladder: {sig(rob.loc['robustness: ladder window'].A_dem_observed)}", "-", "-", "-",
        "results/rq6_frontier.csv", "derived")
    f = o.loc[("FDH peer", "US")]; fe = o.loc[("FDH peer", "EU27")]
    add("Named peers (free disposal hull)", f"US: {f.peer} ({sig(f.A_dem_observed)}); EU27: {fe.peer} ({sig(fe.A_dem_observed)})",
        "-", "-", "-", "results/rq6_frontier.csv", "derived")
    add("Frontier slope", sig(o.loc[(q, 'US')].slope), "ladder points per log unit of A", "-",
        f"95 % CI {sig(o.loc[(q, 'US')].slope_ci_low)}–{sig(o.loc[(q, 'US')].slope_ci_high)}", "results/rq6_frontier.csv",
        "benchmark: ~0.6 crude cross-country (IZA DP 18662)")
    # 6 both levers
    bl = tr.loc[("US", "both levers (observed A_dem, central)")].required_rate
    add("Required sustained decline of T with observed Aᵈᵉᵐ, US lifestyle, 1.7 °C", pct(bl), "per yr", "path",
        f"{pct(tr.loc[('US', 'both levers (observed A_dem, CI high)')].required_rate)}–"
        f"{pct(tr.loc[('US', 'both levers (observed A_dem, CI low)')].required_rate)} (observed Aᵈᵉᵐ CI)",
        "results/rq1_required_rate.csv", "derived")
    r5 = rq5[(rq5.P_label == "now") & (rq5.reference == "US")].set_index(["frame", "T_scenario", "target_degC"])
    m5 = mc.set_index(["frame", "reference", "T_scenario", "target_degC"])
    for sc in ("BAU", "Ambitious", "Extreme"):
        x = r5.loc[("path", sc, T)]
        mm = m5.loc[("path", "US", sc, T)]
        add(f"Required Aᵈᵉᵐ*, US lifestyle, 1.7 °C, {cfg['t_scenarios'][sc]['label']}",
            sig(x.A_dem_required_central) if x.status_central != "floor fails" else "floor fails", "-", "path",
            f"MC median {sig(mm.A_dem_required_median)} (90 %: {sig(mm.A_dem_required_p05)}–{sig(mm.A_dem_required_p95)}); "
            f"observed suffices in {pct(mm.prob_required_le_observed)} of draws",
            "results/rq5_required_dematerialism.csv; results/montecarlo_required_dematerialism.csv", "derived")
    x = r5.loc[("static", "Ambitious", T)]
    add("Required Aᵈᵉᵐ*, US, 1.7 °C, Ambitious, static frame (robustness)", sig(x.A_dem_required_central), "-", "static", "-",
        "results/rq5_required_dematerialism.csv", "derived")
    x2 = r5.loc[("path", "Ambitious", 2.0)]; x3 = r5.loc[("path", "Extreme", 2.0)]
    add("Required Aᵈᵉᵐ*, US, 2.0 °C: Ambitious / Extreme", f"{sig(x2.A_dem_required_central)} / {x3.status_central} "
        f"({sig(x3.A_dem_required_central)})", "-", "path", "-", "results/rq5_required_dematerialism.csv", "derived")
    wd = rq5[(rq5.P_label == "now") & (rq5.reference == "World") & (rq5.frame == "path") & (rq5.T_scenario == "Ambitious")
             & (rq5.target_degC == T)].iloc[0]
    add("Required Aᵈᵉᵐ*, world-average lifestyle, 1.7 °C, Ambitious", f"{wd.status_central} ({sig(wd.A_dem_required_central)})",
        "-", "path", "-", "results/rq5_required_dematerialism.csv", "derived")
    eq = rq4[(rq4.P_label == "now") & (rq4.target_degC == T)].set_index(["frame", "T_scenario"])
    add("Equal-share A within the 1.7 °C budget: today's T (static) / historical rate / Ambitious (path)",
        f"{sig(eq.loc[('static', 'Today')].equal_share_A_int2011usd_per_cap)} ({eq.loc[('static', 'Today')].equal_share_lives_like}) / "
        f"{sig(eq.loc[('path', 'BAU')].equal_share_A_int2011usd_per_cap)} ({eq.loc[('path', 'BAU')].equal_share_lives_like}) / "
        f"{sig(eq.loc[('path', 'Ambitious')].equal_share_A_int2011usd_per_cap)} ({eq.loc[('path', 'Ambitious')].equal_share_lives_like})",
        "2011 int-$ per person per yr", "static / path", "nearest GDP per capita in the frontier sample",
        "results/rq4_cost_of_existing.csv", "derived")
    add("Population now / peak", f"{sig(pop.loc['now'].P_persons / 1e9, 3)} / {sig(pop.loc['peak'].P_persons / 1e9, 3)} "
        f"(peak in {int(pop.loc['peak'].year)})", "bn", "-", "-", "data/processed/population.csv", "OWID; UN WPP 2024 medium variant")
    add("T at the budget base year (path start)", sig(scenarios.t0_path(cfg, units.reset_index()), 3), "kg CO₂ per 2011 int-$",
        "path", "-", "-", "derived: 2022 T carried to 2026 at the historical rate")

    lines = ["# Key numbers", "",
             "Generated by `src/keynumbers.py` from the results CSVs; do not edit by hand. Two significant figures. "
             "Frame: *path* = cumulative emissions along a declining-T path against the budget (main); "
             "*static* = annual impact at the 2050 endpoint T against budget ÷ horizon (robustness). "
             "Scenarios are counterfactuals (whole population at the reference GDP per capita), not forecasts.", "",
             "| # | Quantity | Value | Unit | Frame | Uncertainty / range | From | Source |",
             "|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        lines.append(f"| {i} | " + " | ".join(str(v) for v in r) + " |")
    (RES / "key_numbers.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
